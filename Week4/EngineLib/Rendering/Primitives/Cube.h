// 원점(0,0,0)이 큐브의 중심. 각 축으로 -0.5 ~ +0.5, 한 변 1.0
// (예전에는 원점이 최소 코너였다. 중심 정렬로 바꾸면서 -0.5 만큼 이동시켰다)
//
// 정점 색은 Triangle_vertices 처럼 순색을 보간하는 그라데이션인데,
// 색을 좌표만의 함수로 두지 않고 "면마다" 따로 준다.
//
// 좌표만의 함수(rgb = 좌표 + 0.5)로 두면 두 면이 공유하는 모서리에서 양쪽이
// 같은 두 코너 색 사이를 같은 식으로 보간해, 모서리 위의 색이 수학적으로 완전히
// 같아진다. 그러면 어떤 색을 고르든 경계가 보이지 않는다. 그래서 면별로 나눴다.
//
// 경계는 밝기가 아니라 색상(hue) 차이로 만든다. 밝기를 깎지 않으므로 쨍한
// 느낌이 죽지 않는다.
//
//   ±X 면 : R = dom,          G = (y+0.5)*k,  B = (z+0.5)*k     빨강 계열
//   ±Y 면 : R = (x+0.5)*k,    G = dom,        B = (z+0.5)*k     초록 계열
//   ±Z 면 : R = (x+0.5)*k,    G = (y+0.5)*k,  B = dom           파랑 계열
//
//        + 면 : dom 1.00, k 0.50        - 면 : dom 0.70, k 0.35
//
// 계열이 3개면 충분한 이유: 큐브는 한 번에 최대 3면만 보이고, 그 3면은 항상
// X/Y/Z 축에서 하나씩이다. 마주보는 두 면은 동시에 보이지 않으므로 계열을
// 공유해도 안전하다. (면 인접 관계가 팔면체 그래프라 3색으로 칠해진다)
//
// k 를 절반으로 잡은 것이 핵심이다. 공유 모서리에서 한쪽은 dom(1.00), 다른 쪽은
// dom*k(0.50) 이라 채널당 0.5 가 튄다. k 를 키우면 면 안쪽 그라데이션은 세지지만
// 그만큼 경계가 약해진다. 이 둘이 유일한 트레이드오프다.
//
// 각 면에서 k 가 곱해진 두 채널이 모두 0 이 되는 코너는 순색이 된다.
//   +X 의 (+,-,-) 는 순수 빨강, +Y 의 (-,+,-) 는 순수 초록,
//   +Z 의 (-,-,+) 는 순수 파랑.
//
// 색은 반드시 위 식으로 계산할 것. 인덱스 버퍼가 없어 코너 하나가 최대 5번
// 중복되는데, 여기서는 그 중복된 정점들이 면마다 다른 색을 갖는 것이 정상이다.
// 다만 같은 면 안에서 같은 좌표는 반드시 같은 색이어야 한다(각 면의 삼각형 2개가
// 코너 2개를 공유한다). 눈대중으로 한 줄만 고치면 그 면에 이상한 줄이 생긴다.
//
// 아래 면 이름표(Front/Top/...)는 예전 Y-up 시절의 잔재라 이 엔진과 맞지 않는다.
